/** Built-in lesson index, generated by tools/build-index.mjs. */
export async function loadIndex() {
  if (indexCache) return indexCache;
  try {
    const res = await fetch('./content/index.json', { cache: 'no-cache' });
    indexCache = res.ok ? (await res.json()).lessons || [] : [];
  } catch {
    indexCache = [];
  }
  return indexCache;
}

/** Every lesson available: built-in + imported, imported first. */
export async function allLessons() {
  const [built, mine] = await Promise.all([loadIndex(), db.all('lessons')]);
  const summaries = mine.map(l => ({
    id: l.id, title: l.title, titleZh: l.titleZh || '', level: l.level,
    type: l.type, topic: l.topic || 'custom', count: l.sentences.length,
    summaryZh: l.summaryZh || '', custom: true, at: l.at || 0,
  }));
  summaries.sort((a, b) => b.at - a.at);
  return [...summaries, ...built];
}

export async function getLesson(id) {
  if (lessonCache.has(id)) return lessonCache.get(id);

  const mine = await db.get('lessons', id);
  if (mine) { lessonCache.set(id, mine); return mine; }

  const res = await fetch(`./content/lessons/${encodeURIComponent(id)}.json`, { cache: 'no-cache' });
  if (!res.ok) throw new Error(`找不到課程 ${id}`);
  const lesson = await res.json();
  lessonCache.set(id, lesson);
  return lesson;
}

export async function saveUserLesson(lesson) {
  lessonCache.delete(lesson.id);
  await db.put('lessons', { ...lesson, at: lesson.at || Date.now() });
}

export async function deleteUserLesson(id) {
  lessonCache.delete(id);
  await db.del('lessons', id);
}

