/** 1–5, from sentence length and how far vocabulary strays from the common core. */
export function scoreDifficulty(sentences) {
  const texts = sentences.map(s => (typeof s === 'string' ? s : s.text));
  if (!texts.length) return 1;

  let words = 0, rare = 0;
  for (const t of texts) {
    for (const w of t.toLowerCase().match(/[a-z']+/g) || []) {
      words++;
      if (!COMMON.has(w.replace(/'(s|t|re|ve|ll|d|m)$/, ''))) rare++;
    }
  }
  const avgLen = words / texts.length;
  const rareRatio = words ? rare / words : 0;

  // Roughly: 9-word common-vocabulary sentences → 1; 24-word rare-heavy → 5.
  const lenScore  = Math.min(5, Math.max(1, (avgLen - 6) / 3.6));
  const vocabScore = Math.min(5, Math.max(1, rareRatio / 0.11));
  return Math.max(1, Math.min(5, Math.round(lenScore * 0.55 + vocabScore * 0.45)));
}

/** Words-per-minute a sentence should be read at, given its level. */
export function wpmFor(level) {
  return [0, 100, 115, 130, 145, 160][level] || 130;
}

/** TTS rate multiplier so a level's audio lands near its target WPM. */
export function rateFor(level) {
  return Math.round((wpmFor(level) / 150) * 100) / 100;
}
